# Standardize CDFW tide codes
standardize_tide_code <- function(df_data) {
  # Check if df_data is a non-empty data.frame
  check_output_df(df_data)

  df_data |>
    dplyr::mutate(
      Tide = dplyr::case_match(
        .data$Tide,
        1 ~ "High Slack",
        2 ~ "Ebb",
        3 ~ "Low Slack",
        4 ~ "Flood"
      )
    )
}
